// Compiles the stylesheet (src/styles/calendarkit.css, Tailwind v4, `ck:` prefix) into
// dist/styles.css (`calendarkit-pro/styles.css`) and into src/styles/css.generated.ts, the string
// the Scheduler injects. `--watch` rebuilds when a source file changes (run it next to `next dev`).
import postcss from 'postcss'
import tailwind from '@tailwindcss/postcss'
import { existsSync, mkdirSync, readFileSync, watch, writeFileSync } from 'node:fs'

const ENTRY = 'src/styles/calendarkit.css'
const MODULE = 'src/styles/css.generated.ts'

const writeIfChanged = (file, content) => {
  if (existsSync(file) && readFileSync(file, 'utf8') === content) return
  writeFileSync(file, content)
}

async function build() {
  const { css } = await postcss([tailwind({ optimize: { minify: true } })]).process(readFileSync(ENTRY, 'utf8'), { from: ENTRY })
  mkdirSync('dist', { recursive: true })
  writeIfChanged('dist/styles.css', css)
  writeIfChanged(MODULE, `// Generated by scripts/build-css.mjs from ${ENTRY}: do not edit.\nexport const css = ${JSON.stringify(css)}\n`)
  return css
}

const css = await build()
console.log(`styles: ${(css.length / 1024).toFixed(1)} kB → dist/styles.css, ${MODULE}`)

if (process.argv.includes('--watch')) {
  let timer
  watch('src', { recursive: true }, (_event, file) => {
    if (!file || file.endsWith('css.generated.ts') || !/\.(tsx?|css)$/.test(file)) return
    clearTimeout(timer)
    timer = setTimeout(() => build().then(() => console.log(`styles rebuilt (${file})`), console.error), 50)
  })
  console.log('watching src/ for style changes')
}
